package com.mlmvpn.scanner.utils

/**
 * Chinese templates for tr() texts that contain $ interpolations.
 *
 * tr() receives the already-interpolated English string, so these texts cannot be
 * keyed literally like ZhTrData. Each entry stores the static segments of the English
 * template (the parts around the interpolated values) plus a Chinese template whose
 * {0}, {1}, ... placeholders mark where the captured values go. Entries are ordered
 * by total static length, most specific first: a longer static anchor is the more
 * distinctive template, so the first match in list order is the right one.
 *
 * Generated offline from the tr() call sites in this source tree and verified by
 * simulation: every template, instantiated with sample values, resolves to itself.
 */
internal class ZhTemplate(val segments: Array<String>, val zh: String) {

    /** Returns the captured values in order, or null when [s] does not match. */
    fun match(s: String): List<String>? {
        val n = segments.size - 1
        if (n <= 0) return null
        val caps = ArrayList<String>(n)
        var pos = 0
        val first = segments[0]
        if (first.isNotEmpty()) {
            if (!s.startsWith(first)) return null
            pos = first.length
        }
        for (i in 1 until n) {
            val seg = segments[i]
            val idx = s.indexOf(seg, pos)
            if (idx < 0) return null
            caps.add(s.substring(pos, idx))
            pos = idx + seg.length
        }
        val last = segments[n]
        if (last.isNotEmpty()) {
            val start = s.length - last.length
            if (start < pos || !s.endsWith(last)) return null
            caps.add(s.substring(pos, start))
        } else {
            caps.add(s.substring(pos))
        }
        return caps
    }

    /** Fills the {0}, {1}, ... placeholders of the Chinese template with [caps]. */
    fun render(caps: List<String>): String {
        val sb = StringBuilder(zh.length + 16)
        var i = 0
        while (i < zh.length) {
            if (zh[i] == '{') {
                val end = zh.indexOf('}', i)
                if (end > i) {
                    val num = zh.substring(i + 1, end).toIntOrNull()
                    if (num != null && num in caps.indices) {
                        sb.append(caps[num])
                        i = end + 1
                        continue
                    }
                }
            }
            sb.append(zh[i])
            i++
        }
        return sb.toString()
    }
}

